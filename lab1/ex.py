import math

print("--- 1. CÁC HẰNG SỐ TOÁN HỌC (Math Constants) ---")
print("Số Euler (math.e):", math.e)
print("Dương vô cùng (math.inf):", math.inf)
print("Không phải số (math.nan):", math.nan)
print("Số PI (math.pi):", math.pi)
print("Số Tau (math.tau):", math.tau)

print("\n--- 2. CÁC HÀM LÀM TRÒN & TRỊ TUYỆT ĐỐI ---")
print("Làm tròn lên (math.ceil(1.4)):", math.ceil(1.4))
print("Làm tròn xuống (math.floor(1.4)):", math.floor(1.4))
print("Cắt bỏ phần thập phân (math.trunc(1.9)):", math.trunc(1.9))
print("Giá trị tuyệt đối (math.fabs(-7.25)):", math.fabs(-7.25))

print("\n--- 3. LŨY THỪA, CĂN BẬC & LOGARIT ---")
print("Lũy thừa 2 mũ 3 (math.pow(2, 3)):", math.pow(2, 3)) 
print("Căn bậc 2 của 64 (math.sqrt(64)):", math.sqrt(64))
print("e mũ 2 (math.exp(2)):", math.exp(2))
print("Logarit tự nhiên ln(e) (math.log(math.e)):", math.log(math.e))
print("Logarit cơ số 10 của 100 (math.log10(100)):", math.log10(100))

print("\n--- 4. LƯỢNG GIÁC (Trigonometry) ---")
print("Đổi 180 độ sang radian (math.radians(180)):", math.radians(180))
print("Đổi pi radian sang độ (math.degrees(math.pi)):", math.degrees(math.pi))
print("Sin của pi/2 (math.sin(math.pi/2)):", math.sin(math.pi/2))
print("Cos của pi (math.cos(math.pi)):", math.cos(math.pi))

print("\n--- 5. CÁC HÀM TOÁN HỌC ĐẶC BIỆT KHÁC ---")
print("Giai thừa của 5 (math.factorial(5)):", math.factorial(5))
print("Ước chung lớn nhất của 10 và 15 (math.gcd(10, 15)):", math.gcd(10, 15))
print("Tổ hợp chập 2 của 5 (math.comb(5, 2)):", math.comb(5, 2))
print("Tích các phần tử trong tập [2, 3, 4] (math.prod([2, 3, 4])):", math.prod([2, 3, 4]))